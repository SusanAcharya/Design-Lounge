export function startsOn(surface: Surface) {
  const rank = new Map(ORDER.map((id, i) => [id, i]));
  return STARTS.filter((s) => s.surface === surface).sort((a, b) => (rank.get(a.id) ?? 99) - (rank.get(b.id) ?? 99));
}

