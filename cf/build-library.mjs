// Runs after `astro build`. Prepares the library for the hosted MCP Worker (cf/mcp.js):
// - cf/library.gen.js: every skill file except the briefs, as one module, so the Worker reads them without a disk.
//   About 1.8 MB raw, 0.4 MB compressed, well inside a free Worker's script limit.
// - dist/_mcp/briefs/<id>.md: the briefs (11 MB), served as static files. The Worker fetches one when get_piece asks.
// The skill folder stays the one source of truth: nothing here edits a rule, it only copies.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skill = path.join(root, 'skills', 'design-lounge');
const dist = path.join(root, 'dist');
const KEEP = /\.(md|json|txt|css)$/;

const files = {};
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    const rel = path.relative(skill, full).split(path.sep).join('/');
    if (e.isDirectory()) { if (rel !== 'library/briefs') walk(full); }
    else if (KEEP.test(e.name)) files[`/skill/${rel}`] = fs.readFileSync(full, 'utf8');
  }
};
walk(skill);
files['/mcp/package.json'] = fs.readFileSync(path.join(root, 'mcp', 'package.json'), 'utf8');
if (!files['/skill/library/map.json'] || !files['/skill/library/index.json']) throw new Error('build-library: the skill library is missing map.json or index.json');

fs.writeFileSync(path.join(root, 'cf', 'library.gen.js'),
  `// Generated by cf/build-library.mjs from skills/design-lounge. Do not edit.\nexport default ${JSON.stringify(files)};\n`);

const briefsFrom = path.join(skill, 'library', 'briefs');
const briefsTo = path.join(dist, '_mcp', 'briefs');
if (!fs.existsSync(dist)) throw new Error('build-library: run astro build first, dist/ is missing');
fs.rmSync(briefsTo, { recursive: true, force: true });
fs.mkdirSync(briefsTo, { recursive: true });
let n = 0;
for (const f of fs.readdirSync(briefsFrom)) if (f.endsWith('.md')) { fs.copyFileSync(path.join(briefsFrom, f), path.join(briefsTo, f)); n++; }

const kb = (s) => `${Math.round(s / 1024)} KB`;
console.log(`build-library: ${Object.keys(files).length} files in cf/library.gen.js (${kb(JSON.stringify(files).length)}), ${n} briefs in dist/_mcp/briefs`);
